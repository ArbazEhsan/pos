<script type="text/javascript">
function printDiv(divName) {
     var printContents = document.getElementById(divName).innerHTML;
     var originalContents = document.body.innerHTML;
     document.body.innerHTML = printContents;
     window.print();
     document.body.innerHTML = originalContents;
}

function myFunction() {
  // Declare variables 
  var input, filter, table, tr, td, i;
  input = document.getElementById("myInput");
  filter = input.value.toUpperCase();
  table = document.getElementById("myTable");
  tr = table.getElementsByTagName("tr");

  // Loop through all table rows, and hide those who don't match the search query
  for (i = 0; i < tr.length; i++) {
    td = tr[i].getElementsByTagName("td")[1];
    if (td) {
      if (td.innerHTML.toUpperCase().indexOf(filter) > -1) {
        tr[i].style.display = "";
      } else {
        tr[i].style.display = "none";
      }
    } 
  }
}

function getReport(argument) {
	if(!$("#lockForm")[0].checkValidity()){
		$("#lockForm").find("#submit-hidden").click();
	}
	else {
		var formData = new FormData($("#lockForm")[0]);
		$.ajax({
	        url: "operation.php?from=swpr&operation=show",
	        type: 'POST',
	        data: formData,
	        async: false,
	        success: function (info) {
		 		// alert(info);
		 		var data = info.split("|"); 
		   		$("#tableData").html(data[0]);
		   		$("#from").html(data[1]);
		   		$("#to").html(data[2]);
		   		$("#productName").html(data[3]);
	        },
	        cache: false,
	        contentType: false,
	        processData: false
	    });
	}
}
